CREATE TABLE company (
    COMPANY              INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    NAME        		VARCHAR(100) UNIQUE NOT NULL
);

CREATE TABLE branch (
    BRANCH             INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    NAME        		VARCHAR(100) UNIQUE NOT NULL,
    COMPANY				INT UNSIGNED,
        FOREIGN KEY (COMPANY) REFERENCES COMPANY(COMPANY)
);

CREATE TABLE user (
    USER              INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    USERNAME        VARCHAR(100) UNIQUE NOT NULL,
    PASSWORD   		VARCHAR(255) NOT NULL,
    NAME	     	VARCHAR(100),
    LASTLOGIN     	DATETIME,
    ROLE			INT UNSIGNED,
    COMPANY			INT UNSIGNED,
    BRANCH 			INT UNSIGNED,
    ISACTIVE       	BOOLEAN DEFAULT TRUE,
    INSERTDATE	    DATETIME DEFAULT CURRENT_TIMESTAMP,
    UPDATEDATE      DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY (COMPANY) REFERENCES COMPANY(COMPANY),
    FOREIGN KEY (BRANCH) REFERENCES BRANCH(BRANCH)
    
);

CREATE TABLE device (
    device           INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, -- Κωδικός συσκευής
    code         VARCHAR(100) NOT NULL UNIQUE,            -- Ονομαστικός κωδικός συσκευής
    name         VARCHAR(100),                            -- Ονομασία
    location     VARCHAR(255),                            -- Τοποθέτηση (μέσα στον χώρο)
    awaketime    DATETIME,                                -- Ημ/νία έναρξης λειτουργίας
    url          VARCHAR(255),                            
	COMPANY			INT UNSIGNED,
    BRANCH 			INT UNSIGNED,
    INSERTDATE	    DATETIME DEFAULT CURRENT_TIMESTAMP,
    UPDATEDATE      DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY (COMPANY) REFERENCES COMPANY(COMPANY),
    FOREIGN KEY (BRANCH) REFERENCES BRANCH(BRANCH)
);