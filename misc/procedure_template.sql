CREATE PROCEDURE GetPromoLinesByCarousel (
    IN P_CAROUSEL INT
)
BEGIN
	SELECT 
		PR.PROMOLINES,
        PR.CHANCE,
        PRO.CODE AS PROMOCODE,
		P.NAME AS PRODUCTNAME,
        PRO.DISCOUNT
	FROM
		PROMOLINES PR
	INNER JOIN 
		PROMO PRO ON PRO.PROMO = PR.PROMO
	INNER JOIN 
		PRODUCT P ON P.PRODUCT = PRO.PRODUCT
	WHERE 
		PR.MINIGAME = P_CAROUSEL;
END //

DELIMITER ;
