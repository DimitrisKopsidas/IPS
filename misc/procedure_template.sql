CREATE PROCEDURE GetCarouselSettingsCarouselId (IN p_carousel INT)
BEGIN
	SELECT 
		PROMO.PROMO,
		PRODUCT.NAME as PRODUCTNAME,
		PRODUCT.PRODUCT as PRODUCT,
		TYPE.NAME as TYPENAME,
		MAKER.NAME as MAKERNAME,
		PROMO.DISCOUNT,
		PROMO.DAYSTOLIVE,
		PROMOLINES.CHANCE
	FROM 
		PROMO
	LEFT JOIN 
		PRODUCT ON PRODUCT.PRODUCT = PROMO.PRODUCT
	LEFT JOIN 
		PROMOLINES ON PROMOLINES.PROMO = PROMO.PROMO
	LEFT JOIN 
		MINIGAME ON MINIGAME.MINIGAME = PROMOLINES.MINIGAME
	LEFT JOIN 
		MAKER ON MAKER.MAKER = PROMO.MAKER
	LEFT JOIN 
		TYPE ON TYPE.TYPE = PROMO.TYPE
	WHERE 
		M.MINIGAME = p_carousel;
END //

DELIMITER ;
